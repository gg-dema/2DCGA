def blade_gp(a, b):
    """
    Product of two orthogonal basis blades.

    Returns:
        coefficient, output_mask
    """
    sign = 1.0

    # Sign generated by reordering basis vectors
    for i in range(DIM): # ps: dim = 4
        if (a >> i) & 1: 
            # a >> i : put the i-th bit at position 0
            # then select just the position 0 bit of a (with & 1)
            # (AKA  "does blade a contain basis vector i?")

            # count the number of bits set in b that are lower than i
            
            # 1 << i	        single bit at position i ->      building block for masks
            # (1 << i) - 1	    all bits below position i ->	"positions that come before i"
            # b & ((1<<i)-1)	b's bits below position i ->	"how many of b's factors sit before this a-factor"

            lower_bits_b = b & ((1 << i) - 1)
            if lower_bits_b.bit_count() % 2:
                sign *= -1.0  # swapping impose a sing change

    # Metric factors from repeated basis vectors
    common = a & b  # shared bit 
    # simplify commond basis according to the metric
    for i in range(DIM):
        if (common >> i) & 1:
            sign *= METRIC[i]

    # a ^ b : surviving basis vectors of the output blade
    return sign, a ^ b

def build_gp_table():
    """
    T[i,j,k] is the coefficient of blade k in blade_i * blade_j.
    """
    T = np.zeros((NBLADES, NBLADES, NBLADES))

    for i in range(NBLADES):
        for j in range(NBLADES):
            coefficient, k = blade_gp(i, j)
            T[i, j, k] = coefficient

    return T

def build_outer_table():
    table = np.zeros((NBLADES, NBLADES, NBLADES))

    for i in range(NBLADES):
        for j in range(NBLADES):
            if i & j == 0:
                coefficient, k = blade_gp(i, j)
                table[i, j,k] = coefficient

    return table

def build_inner_table():
    table = np.zeros((NBLADES, NBLADES, NBLADES))

    for i in range(NBLADES):
        grade_i = blade_grade(i)

        for j in range(NBLADES):
            grade_j = blade_grade(j)
            coefficient, k = blade_gp(i, j)

            if blade_grade(k) == abs(grade_i - grade_j):
                table[i, j, k] = coefficient

    return table


def generate_operator(table):
    return lambda a, b: np.einsum("...i,...j,ijk->...k", a, b, table)

