import numpy as np

DIM = 4
NBLADES = 2**DIM

# e1² = e2² = ep² = +1, en² = -1
METRIC = np.array([1.0, 1.0, 1.0, -1.0])



def blade_grade(mask):
    return mask.bit_count()

def basis(mask):
    x = np.zeros(16)
    x[mask] = 1.0
    return x


"""
ORDER OF THE BASIS
0: 1     |  4: ep      | 8:  en       | 12: ep,en
1: e1    |  5: e1,ep   | 9:  e1,en    | 13: e1,ep,en
2: e2    |  6: e2,ep   | 10: e2,en    | 14: e2,ep,en
3: e1,e2 |  7: e1,e2,ep| 11: e1,e2,en | 15: e1,e2,ep,en
"""

scalar = basis(0)
e1     = basis(1)
e2     = basis(2)
ep     = basis(4)
en     = basis(8)
pseudo = basis(15)
eo   = 0.5 * (en - ep)
einf = en + ep

